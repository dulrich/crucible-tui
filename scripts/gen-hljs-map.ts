/**
 * Generates `crates/mdview/src/hljs_map.rs`: the highlight.js-name → syntect-syntax table both
 * Rust consumers of a fence language (the renderer's resolver and `mdview highlight-as`'s
 * validator) look through, via `highlight.rs`'s one lookup.
 *
 * Inputs, both read live, never typed from memory:
 *  1. highlight.js (the pinned dependency): every registered language's canonical name, its
 *     display `name`, and its `aliases`.
 *  2. the two-face syntax set the Rust highlighter loads, dumped by
 *     `cargo run --locked -q -p mdview -- __parity syntaxes` (name, fileExtensions, firstLine).
 *
 * Rule: a highlight.js name gets an entry only if syntect's own token lookup (a syntax name,
 * case-insensitive, or a file extension) does **not** already find it, and one of its
 * language's two own spellings does — its canonical name, then its display name. Aliases are
 * never candidates: short ones collide with unrelated syntect extensions (`re`, `m`).
 * Names neither finds stay unsupported. Rust-only names are untouched (the table only adds).
 *
 * `--check` renders to memory and fails if the committed file differs. A scripts/ DAG leaf.
 */
import hljs from "highlight.js";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const OUT = join(ROOT, "crates/mdview/src/hljs_map.rs");

interface Syntax {
  name: string;
  fileExtensions: string[];
}

const dump = Bun.spawnSync(["cargo", "run", "--locked", "-q", "-p", "mdview", "--", "__parity", "syntaxes"], {
  cwd: ROOT,
  stderr: "pipe",
});
if (dump.exitCode !== 0) {
  console.error(`gen-hljs-map: dumping the syntect set failed: ${dump.stderr.toString().trim()}`);
  process.exit(1);
}
const syntaxes: Syntax[] = dump.stdout
  .toString()
  .split("\n")
  .filter((l) => l.trim() !== "")
  .map((l) => JSON.parse(l) as Syntax);

/** syntect's `find_syntax_by_token`: an extension (case-insensitive), else a name. */
function byToken(token: string): string | undefined {
  const lower = token.toLowerCase();
  for (const s of syntaxes) if (s.fileExtensions.some((e) => e.toLowerCase() === lower)) return s.name;
  for (const s of syntaxes) if (s.name.toLowerCase() === lower) return s.name;
  return undefined;
}

const entries = new Map<string, string>();
for (const language of hljs.listLanguages()) {
  const def = hljs.getLanguage(language);
  if (def === undefined) continue;
  const aliases = (def.aliases ?? []).map((a) => a.toLowerCase());
  const names = [language.toLowerCase(), ...aliases];
  const candidates = [language, def.name ?? ""].filter((c) => c !== "");
  for (const name of names) {
    if (byToken(name) !== undefined || entries.has(name)) continue;
    for (const candidate of candidates) {
      const target = byToken(candidate);
      if (target !== undefined) {
        entries.set(name, target);
        break;
      }
    }
  }
}

/**
 * Reviewed pairs the spelling rule cannot reach: the highlight.js language's own names share no
 * token with the syntect grammar that covers it (e.g. hljs `shell` is "Shell Session"). Each key
 * must be a real highlight.js name and each target a syntax in the dumped set, or the generator
 * fails; a key the rule above already resolves is an error too, so this list cannot shadow it.
 * Deliberately absent, because two-face has no grammar for the language: powershell, vbnet,
 * scheme, handlebars, the `*-repl` sessions, and the rest the WP-6b report lists.
 */
const REVIEWED: Record<string, string> = {
  shell: "Bourne Again Shell (bash)",
  console: "Bourne Again Shell (bash)",
  sql_more: "SQL",
  mysql: "SQL",
  oracle: "SQL",
  pgsql: "SQL",
  postgres: "SQL",
  postgresql: "SQL",
  dos: "Batch File",
  apache: "Apache Conf",
  apacheconf: "Apache Conf",
  fortran: "Fortran (Modern)",
  delphi: "Pascal",
  dfm: "Pascal",
  freepascal: "Pascal",
  lazarus: "Pascal",
  lfm: "Pascal",
  lpr: "Pascal",
  django: "HTML (Jinja2)",
  x86asm: "x86_64 Assembly",
  arduino: "C++",
  ino: "C++",
  "php-template": "PHP",
};
const hljsNames = new Set<string>();
for (const language of hljs.listLanguages()) {
  hljsNames.add(language.toLowerCase());
  for (const alias of hljs.getLanguage(language)?.aliases ?? []) hljsNames.add(alias.toLowerCase());
}
for (const [name, target] of Object.entries(REVIEWED)) {
  if (!hljsNames.has(name)) throw new Error(`gen-hljs-map: ${name} is not a highlight.js name`);
  if (!syntaxes.some((s) => s.name === target)) throw new Error(`gen-hljs-map: no syntect syntax "${target}"`);
  if (byToken(name) !== undefined || entries.has(name)) throw new Error(`gen-hljs-map: ${name} already resolves`);
  entries.set(name, target);
}

const rows = [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const rendered = `// @generated by scripts/gen-hljs-map.ts — do not edit; run \`bun run scripts/gen-hljs-map.ts\`.
// Inputs: highlight.js@${(hljs as unknown as { versionString?: string }).versionString ?? "unknown"} (canonical names, display names, aliases)
// and the two-face syntax set (\`mdview __parity syntaxes\`, ${syntaxes.length} syntaxes).
// highlight.js names syntect's token lookup misses, mapped to the syntect syntax name one of
// the same language's other spellings resolves to. Included by \`highlight.rs\`.
#[rustfmt::skip]
pub const HLJS_TO_SYNTECT: &[(&str, &str)] = &[
${rows.map(([k, v]) => `    (${JSON.stringify(k)}, ${JSON.stringify(v)}),`).join("\n")}
];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // A missing file is stale too; `current` stays empty and fails the comparison below.
  }
  if (current !== rendered) {
    console.error("gen-hljs-map: crates/mdview/src/hljs_map.rs is stale; run bun run scripts/gen-hljs-map.ts");
    process.exit(1);
  }
  console.log(`gen-hljs-map: up to date (${rows.length} names)`);
} else {
  writeFileSync(OUT, rendered);
  console.log(`gen-hljs-map: wrote ${rows.length} names`);
}
